type Ctx = {
  lang: Lang; setLang: (l: Lang) => void; dir: "ltr" | "rtl"; locale: string;
  t: (s: string, vars?: Record<string, string | number>) => string;
  fmt: (n: number, opts?: Intl.NumberFormatOptions) => string;
  fmtDate: (iso: string) => string;
};
const I18nCtx = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("it");
  useEffect(() => {
    try {
      const saved = window.localStorage.getItem("argus-total-lang") as Lang | null;
      if (saved && LANGS.some((l) => l.code === saved)) setLang(saved);
    } catch { /* SSR/no-storage */ }
  }, []);
  // aggiorna lingua e direzione del documento (RTL per l'arabo)
  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
      document.documentElement.dir = RTL_LANGS.includes(lang) ? "rtl" : "ltr";
    }
  }, [lang]);
  const set = (l: Lang) => {
    setLang(l);
    try { window.localStorage.setItem("argus-total-lang", l); } catch { /* */ }
  };
  const t = (s: string, vars?: Record<string, string | number>) => {
    let out = lang === "it" ? s : (TR[lang]?.[s] ?? s);
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
    return out;
  };
  const dir: "ltr" | "rtl" = RTL_LANGS.includes(lang) ? "rtl" : "ltr";
  const locale = LOCALES[lang] || "en-US";
  const fmt = (n: number, opts?: Intl.NumberFormatOptions) => {
    try { return new Intl.NumberFormat(locale, opts).format(n); }
    catch { return String(n); }
  };
  const fmtDate = (iso: string) => {
    try { return new Date(iso + "T00:00:00").toLocaleDateString(locale); }
    catch { return iso; }
  };
  return <I18nCtx.Provider value={{ lang, setLang: set, dir, locale, t, fmt, fmtDate }}>{children}</I18nCtx.Provider>;
}

export function useI18n(): Ctx {
  const c = useContext(I18nCtx);
  if (!c) throw new Error("useI18n deve stare dentro <I18nProvider>");
  return c;
}
