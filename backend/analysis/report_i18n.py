DATE_FMT = {
    "en": "%Y-%m-%d", "hu": "%Y. %m. %d.", "af": "%Y/%m/%d", "zh": "%Y年%m月%d日",
    "de": "%d.%m.%Y", "ro": "%d.%m.%Y", "pl": "%d.%m.%Y", "bg": "%d.%m.%Y",
    "ru": "%d.%m.%Y", "kk": "%d.%m.%Y",
    # default (romanze, ms, id, vi, ar): %d/%m/%Y
}


def fmt_num(lang: str, value, decimals: int = 0) -> str:
    try:
        v = float(value)
    except (TypeError, ValueError):
        return str(value)
    grp, dec = NUM.get(lang, (",", "."))
    neg = v < 0
    s = f"{abs(v):.{decimals}f}"
    intp, _, frac = s.partition(".")
    parts = []
    while len(intp) > 3:
        parts.insert(0, intp[-3:]); intp = intp[:-3]
    parts.insert(0, intp)
    out = grp.join(parts)
    if frac:
        out += dec + frac
    return ("-" if neg else "") + out


def fmt_date(lang: str, d) -> str:
    return d.strftime(DATE_FMT.get(lang, "%d/%m/%Y"))
